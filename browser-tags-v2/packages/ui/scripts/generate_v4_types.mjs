// Regenerates src/shared/native_v4/v4_types.d.ts from the V4 contract's JSON Schema.
//
// The schema lives in realtime (v4/types/schema/v4.schema.json). depict-ui keeps generated types locally for now
// instead of depending on realtime's @depict-ai/types@6, which needs TS 6 and zod 4 (plan 4eez §3, Q3).
//
// Usage (json-schema-to-typescript is not a dependency of this repo, so install it somewhere temporary):
//   git -C ~/src/depict/realtime show origin/main:v4/types/schema/v4.schema.json > /tmp/v4.schema.json
//   npm i --prefix /tmp/json2ts json-schema-to-typescript@15
//   NODE_PATH=/tmp/json2ts/node_modules node scripts/generate_v4_types.mjs /tmp/v4.schema.json <realtime short sha>
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(path.join(process.env.NODE_PATH ?? process.cwd(), "noop.js"));
const { compile } = require("json-schema-to-typescript");

const [schemaPath, revision = "unknown"] = process.argv.slice(2);
if (!schemaPath) throw new Error("usage: generate_v4_types.mjs <v4.schema.json> [realtime revision]");
const outPath = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/shared/native_v4/v4_types.d.ts");

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
// The public V4 shapes the native adapter reads or sends; the frozen V3 shapes in the same schema are left out.
const wanted = [
  "BrowseRequest",
  "BrowseResponse",
  "Product",
  "Variant",
  "Colorway",
  "Price",
  "Color",
  "Facet",
  "ValuesFacet",
  "RangeFacet",
  "FacetValue",
  "Sort",
  "ContentHit",
  "ContentHighlight",
  "ListingRef",
  "ListingHeader",
  "ContentBlock",
  "ListingRequest",
  "ListingResponse",
  "ListingNode",
  "ListingTreeResponse",
  "SuggestRequest",
  "SuggestResponse",
  "Suggestion",
  "ContextResponse",
  "RecommendationsRequest",
  "RecommendationsResponse",
  "RecommendationAnchor",
  "RecentView",
  "ProductsRequest",
  "ProductsResponse",
  "ErrorResponse",
];
const root = {
  $id: "v4",
  title: "V4Types",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(wanted.map(name => [name, { $ref: `#/$defs/${name}` }])),
  $defs: schema.$defs,
};
const ts = await compile(root, "V4Types", {
  bannerComment: `/* eslint-disable */\n/**\n * Generated by json-schema-to-typescript from realtime v4/types/schema/v4.schema.json (${revision}).\n * DO NOT MODIFY BY HAND. Regenerate with browser-tags-v2/packages/ui/scripts/generate_v4_types.mjs (see its header).\n */`,
  additionalProperties: false,
  unreachableDefinitions: false,
  format: true,
  style: { printWidth: 120 },
});
fs.writeFileSync(outPath, ts);
console.log("wrote", outPath);
